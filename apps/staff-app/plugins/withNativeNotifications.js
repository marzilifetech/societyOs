const FILES = {
  'MarziNotificationChannels.kt': CHANNELS_KT,
  'MarziNotificationsModule.kt': MODULE_KT,
  'MarziNativePackage.kt': PACKAGE_KT,
};

/** Drop the Kotlin sources into the (regenerated) android project. */
const withKotlinSources = (config) =>
  withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'java',
        ...JAVA_PACKAGE.split('.'),
      );
      fs.mkdirSync(dir, { recursive: true });
      for (const [name, contents] of Object.entries(FILES)) {
        fs.writeFileSync(path.join(dir, name), contents, 'utf8');
      }
      return cfg;
    },
  ]);

/**
 * Register the package and create channels before React Native loads.
 *
 * Order matters: `ensure()` runs BEFORE `loadReactNative(this)` so a
 * push-triggered process start has its channels in place even if the JS bundle
 * never finishes loading.
 */
const withMainApplicationHooks = (config) =>
  withMainApplication(config, (cfg) => {
    let src = cfg.modResults.contents;

    if (!src.includes('MarziNativePackage()')) {
      const anchor = 'PackageList(this).packages.apply {';
      if (!src.includes(anchor)) {
        throw new Error(
          '[with-native-notifications] Could not find PackageList anchor in MainApplication',
        );
      }
      src = src.replace(anchor, `${anchor}\n              add(MarziNativePackage())`);
    }

    if (!src.includes('MarziNotificationChannels.ensure')) {
      const anchor = 'loadReactNative(this)';
      if (!src.includes(anchor)) {
        throw new Error(
          '[with-native-notifications] Could not find loadReactNative anchor in MainApplication',
        );
      }
      src = src.replace(
        anchor,
        `// Channels must exist before ANY notification can be delivered —\n` +
          `    // including on a process that FCM started to deliver a push to a\n` +
          `    // killed app, where JS may never run. See\n` +
          `    // plugins/withNativeNotifications.js.\n` +
          `    MarziNotificationChannels.ensure(this)\n` +
          `    ${anchor}`,
      );
    }

    cfg.modResults.contents = src;
    return cfg;
  });

/**
 * Declares ACCESS_NOTIFICATION_POLICY so `setBypassDnd(true)` on the emergency
 * channel can take effect once the user grants Do-Not-Disturb access.
 *
 * NOTE — the FCM `default_notification_channel_id` meta-data is deliberately
 * NOT set here. expo-notifications' own manifest mod actively REMOVES that key
 * whenever its `defaultChannel` prop is unset, and it runs after this plugin,
 * so anything written here is silently deleted. It is configured instead via
 * the `expo-notifications` plugin props in app.json (`"defaultChannel":
 * "system"`), which is the supported path and survives plugin reordering.
 */
const withManifestDefaults = (config) =>
  withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;
    manifest['uses-permission'] = manifest['uses-permission'] ?? [];
    const has = (n) => manifest['uses-permission'].some((p) => p.$?.['android:name'] === n);
    if (!has('android.permission.ACCESS_NOTIFICATION_POLICY')) {
      manifest['uses-permission'].push({
        $: { 'android:name': 'android.permission.ACCESS_NOTIFICATION_POLICY' },
      });
    }
    return cfg;
  });

const withNativeNotifications = (config) =>
  withManifestDefaults(withMainApplicationHooks(withKotlinSources(config)));

module.exports = createRunOncePlugin(withNativeNotifications, pkg.name, pkg.version);
