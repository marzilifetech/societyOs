/**
 * The channel FCM falls back to when a message names no/unknown channel.
 * MUST match `expo-notifications.defaultChannel` in app.json — that plugin owns
 * the manifest meta-data (see withManifestDefaults below).
 */
const DEFAULT_CHANNEL_ID = 'system';

const kotlinLongArray = (arr) => `longArrayOf(${arr.join(', ')})`;

function channelKotlin(c) {
  const lines = [
    `      NotificationChannel("${c.id}", "${c.name}", NotificationManager.${c.importance}).apply {`,
    `        lockscreenVisibility = Notification.VISIBILITY_${c.visibility}`,
    `        enableVibration(true)`,
    `        vibrationPattern = ${kotlinLongArray(c.vibration)}`,
    `        group = "${c.group}"`,
  ];
  if (c.lights) {
    lines.push(`        enableLights(true)`);
    lines.push(`        lightColor = BRAND_COLOR`);
  }
  if (c.bypassDnd) {
    // setBypassDnd() silently no-ops unless the user has granted the app
    // Do-Not-Disturb access. Requesting it is a separate user journey; setting
    // it here is still correct because it takes effect the moment access is
    // granted, without needing the channel to be recreated (which Android
    // would not allow anyway).
    lines.push(`        setBypassDnd(true)`);
  }
  lines.push(`      },`);
  return lines.join('\n');
}

const CHANNELS_KT = `package ${JAVA_PACKAGE}

import android.app.Application
import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationChannelGroup
import android.app.NotificationManager
import android.content.Context
import android.os.Build
import android.util.Log

/**
 * Creates every notification channel this app uses, at process start.
 *
 * GENERATED by plugins/withNativeNotifications.js — do not edit in android/,
 * the folder is gitignored and rewritten by \`expo prebuild\`.
 *
 * Called from MainApplication.onCreate() BEFORE loadReactNative(), so the
 * channels exist even when the process was started by FCM to deliver a push to
 * a killed app — i.e. before any JavaScript has run. See the plugin header for
 * the full rationale.
 *
 * Channel creation is idempotent: re-creating an existing channel updates only
 * its name/description. Importance, vibration and DND policy are locked to
 * whatever the channel had when it was FIRST created, which is precisely why
 * getting them right on the very first run matters.
 */
object MarziNotificationChannels {
  private const val TAG = "MarziChannels"
  private const val BRAND_COLOR = 0xFF821A52.toInt()

  /** Channel FCM falls back to; mirrored in the manifest meta-data. */
  const val DEFAULT_CHANNEL_ID = "${DEFAULT_CHANNEL_ID}"

  @Volatile
  private var created = false

  @JvmStatic
  fun ensure(context: Context) {
    if (created) return
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) {
      created = true
      return
    }
    val nm = context.getSystemService(Context.NOTIFICATION_SERVICE) as? NotificationManager
    if (nm == null) {
      Log.w(TAG, "NotificationManager unavailable; channels not created")
      return
    }
    try {
      nm.createNotificationChannelGroups(
        listOf(
${GROUPS.map((g) => `          NotificationChannelGroup("${g.id}", "${g.name}"),`).join('\n')}
        )
      )
      nm.createNotificationChannels(
        listOf(
${CHANNELS.map(channelKotlin).join('\n')}
        )
      )
      created = true
    } catch (t: Throwable) {
      // Never let channel setup take down app start. A failure here degrades
      // to Android's default channel behaviour, which is survivable; a crash
      // in Application.onCreate is not.
      Log.e(TAG, "Failed to create notification channels", t)
    }
  }

  @JvmStatic
  fun isReady(): Boolean = created
}
`;

const MODULE_KT = `package ${JAVA_PACKAGE}

import android.app.NotificationManager
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.provider.Settings
import androidx.core.app.NotificationManagerCompat
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod
import com.facebook.react.bridge.WritableArray

/**
 * Diagnostics + deep-link bridge for Android notification settings.
 *
 * GENERATED by plugins/withNativeNotifications.js.
 *
 * Classic (non-Turbo) ReactContextBaseJavaModule because this app runs on the
 * OLD architecture (\`newArchEnabled: false\` — required by the splash-hang fix).
 *
 * WHY THESE METHODS
 * -----------------
 * The single most common "notifications don't work" report is not a missing
 * app-level permission — it is ONE channel silently switched off, or the whole
 * app blocked at the OS level, both of which the JS-side
 * \`Notifications.getPermissionsAsync()\` reports as \`granted\`. \`getChannelStatus\`
 * exposes the real per-channel importance so the app can tell the user exactly
 * which alert type is muted and deep-link them straight to that channel's
 * system screen instead of dumping them in app settings to hunt for it.
 */
class MarziNotificationsModule(private val reactContext: ReactApplicationContext) :
  ReactContextBaseJavaModule(reactContext) {

  override fun getName(): String = "MarziNotifications"

  override fun getConstants(): MutableMap<String, Any> = hashMapOf(
    // Lets JS skip its own ~14 async channel-creation round-trips on login.
    "channelsReady" to MarziNotificationChannels.isReady(),
    "defaultChannelId" to MarziNotificationChannels.DEFAULT_CHANNEL_ID,
  )

  /** True when the user has not blocked notifications for the whole app. */
  @ReactMethod
  fun areNotificationsEnabled(promise: Promise) {
    try {
      promise.resolve(NotificationManagerCompat.from(reactContext).areNotificationsEnabled())
    } catch (t: Throwable) {
      promise.reject("E_NOTIF_STATE", t)
    }
  }

  /**
   * Per-channel state: importance plus whether the channel's GROUP is blocked
   * (a blocked group mutes every channel in it while each channel still
   * reports its own importance, which is a genuinely confusing Android
   * behaviour worth surfacing explicitly).
   *
   * importance: -1000 = channel missing, 0 = user turned this channel OFF.
   */
  @ReactMethod
  fun getChannelStatus(promise: Promise) {
    try {
      val out: WritableArray = Arguments.createArray()
      if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) {
        promise.resolve(out)
        return
      }
      val nm = reactContext.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
      for (channel in nm.notificationChannels) {
        val map = Arguments.createMap()
        map.putString("id", channel.id)
        map.putString("name", channel.name?.toString() ?: channel.id)
        map.putInt("importance", channel.importance)
        map.putBoolean("blocked", channel.importance == NotificationManager.IMPORTANCE_NONE)
        val groupId = channel.group
        map.putString("groupId", groupId)
        var groupBlocked = false
        if (groupId != null && Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
          groupBlocked = nm.getNotificationChannelGroup(groupId)?.isBlocked ?: false
        }
        map.putBoolean("groupBlocked", groupBlocked)
        out.pushMap(map)
      }
      promise.resolve(out)
    } catch (t: Throwable) {
      promise.reject("E_CHANNEL_STATUS", t)
    }
  }

  /** Open the OS settings page for ONE channel (Android O+), else app settings. */
  @ReactMethod
  fun openChannelSettings(channelId: String, promise: Promise) {
    try {
      val intent = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
        Intent(Settings.ACTION_CHANNEL_NOTIFICATION_SETTINGS)
          .putExtra(Settings.EXTRA_APP_PACKAGE, reactContext.packageName)
          .putExtra(Settings.EXTRA_CHANNEL_ID, channelId)
      } else {
        appSettingsIntent()
      }
      launch(intent)
      promise.resolve(true)
    } catch (t: Throwable) {
      // Some OEM ROMs ship without the per-channel screen. Fall back rather
      // than leaving the user on a dead button.
      try {
        launch(appSettingsIntent())
        promise.resolve(true)
      } catch (t2: Throwable) {
        promise.reject("E_OPEN_CHANNEL", t2)
      }
    }
  }

  /** Open this app's notification settings screen. */
  @ReactMethod
  fun openNotificationSettings(promise: Promise) {
    try {
      launch(appSettingsIntent())
      promise.resolve(true)
    } catch (t: Throwable) {
      promise.reject("E_OPEN_SETTINGS", t)
    }
  }

  private fun appSettingsIntent(): Intent =
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
      Intent(Settings.ACTION_APP_NOTIFICATION_SETTINGS)
        .putExtra(Settings.EXTRA_APP_PACKAGE, reactContext.packageName)
    } else {
      Intent(Settings.ACTION_APPLICATION_DETAILS_SETTINGS)
        .setData(Uri.fromParts("package", reactContext.packageName, null))
    }

  /**
   * Prefer the foreground activity so the settings screen lands on top of the
   * app's own task; only fall back to NEW_TASK from the application context,
   * which on some OEMs otherwise opens settings in a separate recents entry.
   */
  private fun launch(intent: Intent) {
    val activity = reactContext.currentActivity
    if (activity != null) {
      activity.startActivity(intent)
    } else {
      intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
      reactContext.startActivity(intent)
    }
  }
}
`;

