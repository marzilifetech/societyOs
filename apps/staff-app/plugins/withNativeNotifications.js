/**
 * Native (Kotlin) notification channel bootstrap + diagnostics bridge.
 *
 * WHY THIS EXISTS
 * ---------------
 * Channels were created only from JS, inside `registerForPushNotifications()`,
 * which runs *after* the user logs in AND grants POST_NOTIFICATIONS. That
 * leaves a window — every fresh install, and every cold start where FCM
 * launches the process to deliver a push to a killed app — in which the
 * channel a message targets DOES NOT EXIST YET.
 *
 * Android's behaviour in that window is the bug users actually feel:
 *   • FCM falls back to the channel named by the
 *     `default_notification_channel_id` manifest meta-data. That meta-data was
 *     ABSENT, so FCM used its own auto-created "Miscellaneous" channel —
 *     IMPORTANCE_DEFAULT, no heads-up pop, no custom vibration.
 *   • `emergency_sos` (IMPORTANCE_MAX + bypassDnd) therefore did not exist when
 *     the first SOS arrived, so the one notification that must always break
 *     through arrived as a silent tray entry.
 *   • Channel importance is LOCKED at creation time. Once Android has created
 *     "Miscellaneous" for this app, later JS calls cannot upgrade it.
 *
 * Creating the channels in `Application.onCreate` fixes all three: the process
 * that FCM spins up to deliver a push runs `onCreate` *before* the message is
 * dispatched, so every channel is guaranteed to exist with the right
 * importance, vibration pattern and DND policy at the moment of first delivery
 * — with no dependency on the JS bundle having loaded or the user having
 * logged in.
 *
 * It is also faster: `setupAndroidChannels()` in JS was ~14 sequential async
 * bridge round-trips on every login. JS now skips them entirely when this
 * module reports `channelsReady`.
 *
 * WHY A CONFIG PLUGIN AND NOT FILES IN android/
 * ---------------------------------------------
 * `apps/*​/android/` is gitignored and regenerated by `expo prebuild`, so
 * hand-written Kotlin in there is silently discarded — the exact failure mode
 * documented in `withAndroidNoSystemSplash.js` and `withAndroidReleaseSigning.js`.
 *
 * WHAT IS DELIBERATELY *NOT* DONE HERE
 * ------------------------------------
 * No custom `FirebaseMessagingService`. expo-notifications registers its own
 * and handles both notification- and data-messages natively; subclassing or
 * overriding it would mean re-implementing expo's dispatch, tap handling and
 * token plumbing, which is a large regression surface for no delivery gain.
 * The backend already ships a real `android.notification` block alongside the
 * data payload (see backend push.service.ts), so display is native and instant
 * without any JS involvement. The genuine gap was channel *existence*, and
 * that is what this plugin closes.
 */

